<section class="card flush rules" id="regole">
    <div class="card-head"><h2><x-icon name="book" /> Regole di gioco</h2></div>
    <p class="rules-intro">
        Si gioca con il <strong>regolamento dell'Oratorio Cup 2026/2027 del CSI Roma</strong>. Per tutto quello che non è scritto lì valgono le norme CSI e il regolamento tecnico del calcio a 5 FIGC (edizione 2025).
    </p>

    <details class="matchday" open>
        <summary>Lo spirito dell'Oratorio Cup</summary>
        <ul class="rules-list">
            <li><strong>Giocano tutti</strong>, a prescindere dal livello tecnico, fino all'ultima giornata.</li>
            <li>La squadra di casa mette a disposizione un <strong>addetto all'arbitraggio</strong>: un suo dirigente, iscritto nell'albo CSI, che dirige la partita e non può essere in distinta come allenatore o dirigente.</li>
            <li>Nella seconda fase della Fascia Oro arbitra l'<strong>Arbitro Oratorio Cup</strong> (il tesserato che ha superato il corso arbitri CSI Roma): prima quello di casa, altrimenti quello ospite, altrimenti l'addetto all'arbitraggio di casa.</li>
            <li>Dopo il fischio finale c'è il <strong>IV tempo</strong>: la squadra di casa offre un piccolo rinfresco e quella ospite lo condivide. Ogni squadra deve farne <strong>almeno 2 nella prima fase</strong>.</li>
            <li>Alla <strong>festa finale</strong> giocano tutte le squadre, con partite che assegnano ogni posizione, dalla prima all'ultima.</li>
        </ul>
    </details>

    <details class="matchday">
        <summary>Categorie e anni di nascita (2026/2027)</summary>
        <ul class="rules-list">
            <li><strong>Under 8</strong>: 2019-2021, senza sottoquota.</li>
            <li><strong>Under 9</strong>: 2018-2020, con fino a <strong>3 sottoquota</strong> (2021) a partita.</li>
            <li><strong>Under 10</strong>: 2017-2019 (sottoquota 2020) · <strong>Under 11</strong>: 2016-2018 (2019) · <strong>Under 12</strong>: 2015-2017 (2018).</li>
            <li><strong>Under 13</strong>: 2014-2016 (2017) · <strong>Under 14</strong>: 2013-2015 (2016).</li>
            <li><strong>Under 15</strong>: 2012-2014 (2015) · <strong>Under 16</strong>: 2011-2013 (2014) · <strong>Under 17</strong>: 2010-2012 (2013).</li>
            <li><strong>Open</strong>: nati nel 2011 e prima (sottoquota 2012) · <strong>Amatori</strong>: nati nel 1992 e prima (sottoquota 1993).</li>
            <li>Dall'Under 10 in su si può schierare <strong>1 sottoquota a partita</strong>, nato nell'anno indicato tra parentesi. Non sono previsti fuori quota maschili.</li>
            <li>Dall'Under 8 all'Under 17 le squadre possono essere <strong>miste</strong>, con al massimo <strong>2 ragazze fuori quota</strong> (nate l'anno prima della categoria) a partita.</li>
            <li>Le squadre tutte femminili giocano nella <strong>categoria inferiore</strong> dall'Under 8 all'Under 11 e <strong>due categorie sotto</strong> dall'Under 12 all'Under 16 (per esempio, una squadra di ragazze nate 2013-2015 può iscriversi in Under 12).</li>
            <li>Su richiesta della società, un atleta con <strong>disabilità intellettiva o relazionale</strong> certificata può giocare in una categoria di età inferiore.</li>
        </ul>
    </details>

    <details class="matchday">
        <summary>Distinta e documenti</summary>
        <ul class="rules-list">
            <li>Almeno <strong>15 minuti prima</strong> della partita il dirigente responsabile consegna all'addetto all'arbitraggio la <strong>distinta compilata online</strong> e il <strong>tesserino CSI con foto</strong> di ogni atleta e dirigente.</li>
            <li>In distinta vanno fino a <strong>15 giocatori</strong>, il capitano e il vicecapitano, e al massimo un dirigente responsabile, un dirigente accompagnatore e un allenatore.</li>
            <li>Senza tesserino si gioca solo mostrando un documento d'identità originale (sotto i 12 anni, l'autocertificazione con foto).</li>
            <li>Tutti gli atleti vanno tesserati entro il <strong>28 febbraio 2027</strong>; dopo si può aggiungere un solo atleta entro il 21 marzo 2027.</li>
            <li>Una società con più squadre nella stessa categoria non può scambiare i giocatori: ognuno resta con la squadra con cui ha giocato la prima partita.</li>
        </ul>
    </details>

    <details class="matchday">
        <summary>Durata della partita</summary>
        <ul class="rules-list">
            <li><strong>Under 8, 9, 10, 11 e 12</strong>: <strong>3 tempi da 15 minuti</strong>.</li>
            <li><strong>Dall'Under 13 agli Amatori</strong>: <strong>2 tempi da 25 minuti</strong>.</li>
            <li>Ogni squadra ha <strong>un time-out di 1 minuto per tempo</strong>. Lo chiede l'allenatore in panchina o, se manca, solo il capitano.</li>
            <li>Le squadre devono essere in campo pronte all'orario fissato. Con più di <strong>30 minuti di ritardo</strong> si perde la partita <strong>0-6</strong>.</li>
        </ul>
    </details>

    <details class="matchday">
        <summary>Pallone e abbigliamento</summary>
        <ul class="rules-list">
            <li>Fino all'<strong>Under 12</strong>: pallone n. 4 a <strong>rimbalzo normale</strong>. Dall'<strong>Under 13 agli Amatori</strong>: pallone n. 4 a <strong>rimbalzo controllato</strong>.</li>
            <li>La squadra di casa porta almeno 2 palloni regolari, quella ospite almeno 1.</li>
            <li>Maglie uguali e <strong>numerate</strong>. Il portiere ha una maglia diversa da compagni e avversari, o una pettorina.</li>
            <li>Se i colori si confondono, cambia maglia o mette le pettorine la <strong>squadra di casa</strong>.</li>
            <li><strong>Parastinchi</strong>: chi ne è senza può entrare in campo solo se glieli passa un compagno.</li>
            <li>Le scarpe da calcio coi tacchetti sono vietate solo se il proprietario del campo lo ha comunicato per iscritto alla Commissione.</li>
        </ul>
    </details>

    <details class="matchday">
        <summary>Sostituzioni ed espulsioni</summary>
        <ul class="rules-list">
            <li>In campo vanno <strong>5 giocatori per squadra</strong>, portiere compreso.</li>
            <li>Le sostituzioni sono <strong>"volanti" e illimitate</strong>, dalla zona cambi davanti alla propria panchina. Chi esce deve essere fuori dal campo prima che l'altro entri.</li>
            <li>Un giocatore espulso può essere sostituito <strong>allo scadere della sanzione</strong> oppure <strong>appena la squadra avversaria segna</strong>.</li>
        </ul>
    </details>

    <details class="matchday">
        <summary>Il portiere e il retropassaggio</summary>
        <ul class="rules-list">
            <li><strong>Under 8, 9 e 10</strong>: il passaggio volontario al portiere è sempre permesso e lui può prendere il pallone <strong>anche con le mani</strong>.</li>
            <li><strong>Under 11, 12, 13 e 14</strong>: il passaggio al portiere è sempre permesso, ma lui può giocarlo <strong>solo con i piedi</strong>.</li>
            <li><strong>Dall'Under 15 agli Amatori</strong>: il portiere può ricevere un passaggio volontario <strong>una sola volta</strong> e solo con i piedi; per toccare di nuovo il pallone nella sua metà campo deve prima toccarlo un avversario.</li>
            <li>Il portiere può tenere il pallone nella propria metà campo per <strong>al massimo 4 secondi</strong>.</li>
        </ul>
    </details>

    <details class="matchday">
        <summary>Rimesse e calci piazzati</summary>
        <ul class="rules-list">
            <li><strong>Rimessa laterale con i piedi</strong>, a pallone fermo sulla linea, entro <strong>4 secondi</strong>, con gli avversari a 5 metri.</li>
            <li><strong>Rimessa dal fondo</strong>: la fa il portiere con le mani dalla propria area, entro 4 secondi.</li>
            <li>Su punizioni e calci d'angolo gli avversari stanno ad almeno <strong>5 metri</strong>. Il calcio di rigore si batte da <strong>6 metri</strong>.</li>
            <li><strong>Solo Under 8 e Under 9</strong>:
                <ul>
                    <li>non vale il gol segnato direttamente da <strong>calcio d'inizio</strong>, da <strong>rimessa laterale</strong> o da <strong>punizione battuta nella propria metà campo</strong>, anche se un avversario tocca involontariamente il pallone; si riprende con rimessa dal fondo, o con calcio d'angolo se l'ha toccato un avversario;</li>
                    <li>la <strong>rimessa dal fondo</strong> deve fermarsi entro la metà campo;</li>
                    <li><strong>no pressing zone</strong>: durante la rimessa dal fondo gli avversari restano fuori dalla metà campo di chi rimette.</li>
                </ul>
                In caso di infrazione la rimessa si ripete.
            </li>
        </ul>
    </details>

    <details class="matchday">
        <summary>Falli e cartellini</summary>
        <ul class="rules-list">
            <li><strong>Niente falli cumulativi</strong> in tutte le categorie, tranne nelle partite di seconda fase di Under 15, 16, 17, Open e Amatori dirette da arbitri CSI.</li>
            <li>La <strong>bestemmia</strong> si punisce con il <strong>cartellino rosso</strong>.</li>
            <li>Chi viene espulso salta <strong>almeno una giornata</strong>; la squalifica esatta la decide il Giudice Sportivo sul Comunicato Ufficiale.</li>
            <li>Con <strong>3 ammonizioni</strong> nella stessa categoria si salta una giornata. Alla fine della prima fase le ammonizioni si azzerano.</li>
        </ul>
    </details>

    <details class="matchday">
        <summary>Classifica, disciplina e fair play</summary>
        <ul class="rules-list">
            <li><strong>Dall'Under 10 agli Amatori</strong>: <strong>3 punti</strong> a chi vince, <strong>1</strong> a testa per il pareggio, <strong>0</strong> a chi perde.</li>
            <li><strong>Under 8 e Under 9</strong>: contano i tempi vinti. 3 tempi pari: 1 punto a testa. 1 vittoria e 2 pareggi, o 3 vittorie: 3 punti a chi vince. 1 vittoria, 1 sconfitta e 1 pareggio: 1 punto a testa. 2 tempi vinti e 1 perso: 2 punti a chi vince e 1 a chi perde.</li>
            <li>Dall'Under 10 all'Under 14 la <strong>giornata polisportiva</strong> vale come una partita: 3 punti al vincitore di tappa, 1 per la partecipazione, -1 se la squadra non si presenta.</li>
            <li>A parità di punti si guarda la <strong>classifica avulsa</strong>: punti negli scontri diretti, vittorie, differenza reti e gol segnati negli scontri diretti, poi punti disciplina e fair play, infine il sorteggio.</li>
            <li>Nelle partite a eliminazione diretta finite in parità si tirano <strong>5 rigori a testa</strong>, poi a oltranza. Con andata e ritorno contano prima le vittorie e la differenza reti; il gol in trasferta non vale doppio.</li>
            <li><strong>Tabella disciplina</strong>: penalità per parastinchi mancanti, tesserini mancanti, distinta incompleta, referto inviato in ritardo, palloni non regolari, meno di 2 IV tempi e altro. Ogni punto disciplina intero toglie <strong>1 punto in classifica</strong>.</li>
            <li><strong>Tabella fair play</strong>: 0,6 per ogni ammonizione, 1,2 per ogni espulsione, 2 per ogni giornata di squalifica di un atleta, 6 per una rinuncia, 10 per una mancata presentazione. Serve a decidere le parità.</li>
        </ul>
    </details>

    <details class="matchday">
        <summary>Rinunce, rinvii e mancata presentazione</summary>
        <ul class="rules-list">
            <li><strong>Mancata presentazione</strong>: la prima volta sconfitta 0-6 e 1 punto di penalizzazione; la seconda 0-6 e 3 punti di penalizzazione; la terza esclusione dal torneo.</li>
            <li><strong>Rinuncia preventiva</strong>, almeno 48 ore prima: sconfitta 0-6. Se ne può fare una sola; la seconda conta come mancata presentazione.</li>
            <li><strong>Spostare una partita</strong>: ci si accorda con gli avversari e lo si comunica per mail alla Commissione almeno 48 ore prima, aspettando il suo sì. Massimo <strong>3 spostamenti</strong> per squadra.</li>
            <li>Le partite del girone d'andata vanno giocate entro il <strong>28 gennaio 2027</strong>. Nel girone di ritorno non si accettano rinvii a data da destinarsi.</li>
            <li>Entro <strong>48 ore</strong> dalla partita la squadra di casa manda distinte e referto a referti.oratoriocup@csiroma.it e alla squadra avversaria.</li>
        </ul>
    </details>

    <details class="matchday">
        <summary>Sicurezza</summary>
        <ul class="rules-list">
            <li>La squadra di casa deve garantire sul campo un <strong>defibrillatore (DAE)</strong> funzionante e una persona formata a usarlo, indicata nella distinta. Senza DAE la partita non comincia e la squadra di casa la perde a tavolino.</li>
        </ul>
    </details>

